function parseRaw(raw, topic) {
  return raw.trim().split('\n').map((l) => l.trim()).filter(Boolean).map((line, i) => {
    const [en, cz, ph, img] = line.split('|');
    return {
      id: `es-v-${topic}-${i}`,
      topic,
      en: (en || '').trim(),
      cz: (cz || '').trim(),
      phonetic: ph ? `[${ph.trim()}]` : '',
      img: (img || '🇪🇸').trim()
    };
  });
}

export const ES_VOCAB_PACKS = ES_RAW_PACKS.map((p) => ({
  id: p.id,
  topic: p.topic,
  title: p.title,
  icon: p.icon,
  color: p.color,
  words: parseRaw(p.raw, p.topic)
}));

export const ES_VOCABULARY = ES_VOCAB_PACKS.flatMap((p) => p.words);
